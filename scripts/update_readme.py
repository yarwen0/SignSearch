"""Generate every reported quantity directly from raw experiment metrics."""
from pathlib import Path
import json


def main():
    root = Path(__file__).resolve().parents[1]
    m = json.loads((root / "results/metrics.json").read_text())
    config = m["training"]
    data = m["dataset"]
    rows = ["| Model | Split | Top-1 | Top-5 | MRR | Top-1 bootstrap interval |", "|---|---|---|---|---|---|"]
    for model, splits in m["models"].items():
        for split, values in splits.items():
            rows.append(f"| {model} | {split} | {values['top1']} | {values['top5']} | {values['mrr']} | {values['top1_bootstrap_95_ci']} |")
    speed_rows = ["| Export | CPU median ms/clip | CPU p95 ms/clip | Runs | Warmup |", "|---|---|---|---|---|"]
    for name, values in m["cpu_latency"].items():
        speed_rows.append(f"| {name} | {values['median_ms']} | {values['p95_ms']} | {values['runs']} | {values['warmup_runs']} |")
    split_rows = ["| Split | Clips | Signers |", "|---|---|---|"]
    for split, values in data["splits"].items():
        split_rows.append(f"| {split} | {values['clips']} | {values['signers']} |")
    variation = m["models"]["transformer"]["test"]["per_signer"]
    extraction = m["keypoint_extraction"]
    text = f"""# SignSearch

Sign-to-dictionary retrieval for American Sign Language. A clip is represented by upper-body pose and hand landmarks, then ranked against a fixed vocabulary. This is isolated-sign lookup, not sentence translation or a substitute for an interpreter.

## Data and license

This experiment uses a seeded random subset of {data['classes']} glosses present in all official [ASL Citizen](https://www.microsoft.com/en-us/research/project/asl-citizen/) splits. Selection seed: {data['seed']}. The official signer assignments are preserved; tests check for signer and clip overlap.

{chr(10).join(split_rows)}

The dataset is governed by the [Microsoft Research License Terms](https://www.microsoft.com/en-us/research/project/asl-citizen/dataset-license/): non-commercial, non-revenue-generating research only. Videos are personal data. Do not redistribute the dataset, landmarks, or split manifests. The pipeline uses HTTP ranges to retrieve the member list, official split metadata, and selected videos without downloading the complete archive. Downloaded videos are deleted only after successful landmark extraction. Dataset files, landmarks, MediaPipe model files, and checkpoints are ignored by Git. Failed clips are logged locally; training refuses incomplete required splits.

## Method

MediaPipe Tasks HandLandmarker and lite PoseLandmarker run in VIDEO mode. Coordinates are centered at the shoulder midpoint and divided by shoulder width in pixel space. Missing groups remain zero and have explicit masks; missing shoulder anchors are interpolated within a clip. All decoded frames are processed; long clips are sampled and short clips padded to {config['frames']} frames. Features are saved locally as float16.

The transformer projects {config['input_features']} input features to width {config['dim']}, uses {config['layers']} encoder layers and {config['heads']} attention heads, learned positions, masked mean pooling, and a {config['classes']}-class head. A pooled mean/standard-deviation MLP is the baseline. Training uses AdamW, cosine scheduling, label smoothing {config['label_smoothing']}, fixed seed {config['seed']}, and spatial, speed, and mirrored-hand augmentations. Only validation top-1 selects the learning rate and stopping epoch. All hyperparameters and curves are retained in `results/`.

## Measured results

Generated by `scripts/update_readme.py` from `results/metrics.json`; the values below are unrounded proportions. MRR ranks the true gloss against the complete selected vocabulary. Intervals use {m['models']['transformer']['test']['bootstrap_resamples']} bootstrap resamples by clip. The test run happens only after freezing model selection and export configuration.

{chr(10).join(rows)}

{chr(10).join(speed_rows)}

Machine: {m['machine']['cpu']}; RAM bytes: {m['machine']['memory_bytes']}; platform: {m['machine']['platform']}. Latency is CPU inference at batch {m['cpu_latency']['fp32']['batch']}, {m['cpu_latency']['fp32']['frames']} frames, {m['cpu_latency']['fp32']['intra_op_threads']} intra-op threads. Input is synthetic normalized-shape data; timings exclude landmark extraction. Raw latency vectors are retained. FP32 ONNX is checked against PyTorch before test evaluation, and INT8 uses ONNX Runtime dynamic weight quantization.

Concurrent CPU keypoint extraction: median {extraction['median_ms_per_frame']} ms/frame; p95 {extraction['p95_ms_per_frame']} ms/frame; mean {extraction['mean_ms_per_frame']} ms/frame across {extraction['frames']} decoded frames, with {extraction['workers']} worker processes. This measures both landmark detector calls, excluding decoding, model startup, and file IO. It is separate from batch-one model inference latency.

## Reproduce

```sh
python -m venv .venv
.venv/bin/python -m pip install -r requirements.txt
.venv/bin/python scripts/prepare.py
.venv/bin/python -m pytest
.venv/bin/python train.py
.venv/bin/python evaluate.py
.venv/bin/python scripts/update_readme.py
```

After completing the experiment, rank an isolated signing clip with `.venv/bin/python search.py /path/to/clip.mp4`. The command preserves the original clip, deletes its temporary copy and query landmarks, and prints ranked glosses with model probabilities. These probabilities are not calibrated confidence estimates. Exported model files and the local gloss vocabulary must be present.

`results/environment.txt` records the packages used for this run. `results/prepare.log` and `data/extraction.jsonl` retain extraction evidence; the latter is ignored because it contains dataset identifiers. Curves record every training epoch. Raw prediction arrays are retained locally and ignored. `results/test_started.json` freezes the final evaluation boundary; do not remove it or tune on the test results. Re-running evaluation after completion prints the existing metrics. `scripts/run_pipeline.py` coordinates preparation, selection, evaluation, and README generation without evaluating test during training.

## Limits

This is a {data['classes']}-sign subset and is not comparable with the full-vocabulary numbers in the ASL Citizen paper. It uses pose and hand coordinates only, omitting facial expression, appearance, and depth. Horizontal flipping is a training assumption and can change lexical meaning for some signs. MediaPipe errors, occlusion, missing hands, camera framing, and signing variation affect retrieval. The provided dictionary glosses are identifiers rather than translations of all possible meanings.

Held-out signer top-1 varies from {variation['min']} to {variation['max']}, with median {variation['median']}; the complete per-signer counts and scores are in `results/metrics.json`. The clip bootstrap interval does not capture signer-population uncertainty. These measurements describe this dataset subset and recording conditions, not general accessibility effectiveness.
"""
    (root / "README.md").write_text(text)


if __name__ == "__main__":
    main()
